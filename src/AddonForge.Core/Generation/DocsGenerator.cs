using System.Text;
using AddonForge.Core.Analysis;
using AddonForge.Core.Models;

namespace AddonForge.Core.Generation;

/// <summary>
/// Builds DOCS.md and a CHANGELOG.md entry. Deterministic template; the
/// optional LLM-produced summary (if any) is embedded verbatim as a section,
/// never used to decide structure or option values.
/// </summary>
public static class DocsGenerator
{
    public static string BuildDocs(
        AddonGenerationRequest request,
        RepoAnalysisResult analysis,
        Dictionary<string, object> schema,
        bool entrypointWrapped = false,
        bool noShellWithOptions = false,
        bool debugVariantApplied = false,
        IReadOnlyList<string>? persistentPaths = null,
        IReadOnlyList<string>? sharedPaths = null)
    {
        persistentPaths ??= [];
        sharedPaths ??= [];
        var sb = new StringBuilder();
        sb.AppendLine($"# {request.Name}");
        sb.AppendLine();
        sb.AppendLine(request.Description);
        sb.AppendLine();
        sb.AppendLine(request.SourceWebUrl is not null
            ? $"Generated by addon-forge from [{request.SourceRepoUrl}]({request.SourceWebUrl}) @ `{request.Ref}`."
            : $"Generated by addon-forge from `{request.SourceRepoUrl}` @ `{request.Ref}`.");
        sb.AppendLine();

        if (debugVariantApplied)
        {
            sb.AppendLine("## Base image");
            sb.AppendLine();
            sb.AppendLine("This addon's final build stage uses a distroless base image, which normally ships " +
                           "with no shell — addon-forge can't deliver configured options (or render a config " +
                           "file) there without one. Since this was explicitly allowed, its tag was switched " +
                           "to the distroless project's own \"debug\" variant, which includes a minimal shell " +
                           "(busybox) for exactly this purpose. This removes some of the hardening (no shell, " +
                           "no package manager, smaller attack surface) the original image shipped with — an " +
                           "explicit, deliberate trade-off, not addon-forge's default.");
            sb.AppendLine();
        }

        if (request.HostNetwork)
        {
            sb.AppendLine("## Networking");
            sb.AppendLine();
            sb.AppendLine("This addon runs on the host's own network (`host_network: true`) instead of a " +
                           "Docker-managed one - required because the upstream image expects to bind host " +
                           "ports directly rather than go through Docker's own port publishing. Confirmed " +
                           "directly against the Supervisor's own source: once this is set, the ports listed " +
                           "below become **informational only** - the Supervisor drops the port mapping " +
                           "entirely when actually starting the container, since there's nothing for Docker " +
                           "to publish under host networking. The app itself is responsible for actually " +
                           "listening on each of these.");
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(request.DocsSummary))
        {
            sb.AppendLine("## About");
            sb.AppendLine();
            sb.AppendLine(request.DocsSummary);
            sb.AppendLine();
        }

        if (schema.Count > 0)
        {
            sb.AppendLine("## Configuration");
            sb.AppendLine();
            sb.AppendLine("| Option | Type | Notes |");
            sb.AppendLine("|---|---|---|");
            foreach (var (name, type) in schema.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            {
                var notes = type.ToString()!.EndsWith('?') ? "optional, review default before installing" : "required";
                sb.AppendLine($"| `{name}` | `{type}` | {notes} |");
            }

            sb.AppendLine();

            if (entrypointWrapped)
            {
                sb.AppendLine("Home Assistant only writes these to `/data/options.json` — it does not inject " +
                               "them as environment variables on its own. addon-forge wraps this addon's " +
                               "entrypoint (`addon-forge-entrypoint.sh`) to translate that file into real env " +
                               "vars before handing off to the app's own original entrypoint, so the above " +
                               "options reach it the way it actually expects. Home Assistant writes that file " +
                               "readable only by its own Supervisor (mode 600) — this addon's own user, " +
                               "whatever it is, can't open it directly. Rather than becoming root to read it " +
                               "(which broke real apps that fork a child expecting to write to their own " +
                               "PID 1's stdout, e.g. some cron setups — confirmed directly, root doesn't change " +
                               "the app's own user, but the underlying privilege drop does something Linux " +
                               "treats as sensitive enough to block that afterwards, regardless of which tool " +
                               "performs it), `jq` itself (fetched via `COPY --from=ghcr.io/jqlang/jq`) is made " +
                               "setuid-root instead, so it alone can read that one file — nothing in this " +
                               "script or the app it hands off to ever changes user.");
                sb.AppendLine();
            }
            else if (noShellWithOptions)
            {
                sb.AppendLine("**Warning:** this addon's final build stage has no shell (`FROM scratch`, or a " +
                               "distroless image) — addon-forge can't wrap its entrypoint to deliver the " +
                               "options above as environment variables the way it normally would. They're " +
                               "saved when you configure the addon, but the app itself won't receive them " +
                               "unless it reads `/data/options.json` directly.");
                sb.AppendLine();
            }
        }

        if (!string.IsNullOrWhiteSpace(request.ConfigFileDestPath))
        {
            sb.AppendLine("## Config file");
            sb.AppendLine();
            if (entrypointWrapped)
            {
                sb.AppendLine($"This app reads some settings only from `{request.ConfigFileDestPath}`, not " +
                               "environment variables. addon-forge renders that file from a template (filling " +
                               "in the options above wherever it references them, via the same setuid `jq` " +
                               "mentioned above) and writes it there before the app starts. If that render " +
                               "step fails, the unrendered template is written instead (still better than " +
                               "nothing); if even that can't be written at all - no write permission on this " +
                               "path under this addon's own user - a message is logged and the app starts " +
                               "anyway, without it. That destination path has to be writable by whatever user " +
                               "this image actually runs as (check its own USER, if any) - this never crashes " +
                               "the addon over it, but the app itself may not start correctly without a config " +
                               "file it actually needs.");
            }
            else if (noShellWithOptions)
            {
                sb.AppendLine($"**Warning:** this addon's final build stage has no shell (`FROM scratch`, or a " +
                               $"distroless image) — addon-forge can't render and write " +
                               $"`{request.ConfigFileDestPath}` the way it normally would. Nothing is written " +
                               "there automatically.");
            }

            sb.AppendLine();
        }

        if (request.Ingress)
        {
            sb.AppendLine("## Ingress");
            sb.AppendLine();
            sb.AppendLine("This addon was generated with ingress enabled. That only works well if the app " +
                           "itself is ingress-aware (it prefixes its own links/redirects/assets with the " +
                           "path Home Assistant assigns it) — most self-hosted apps aren't, and will show " +
                           "broken pages or 404s under ingress even though the container runs fine. If that " +
                           "happens, disable ingress and expose the port directly instead.");
            sb.AppendLine();
        }

        // A shared path is also effectively kept, not just persistent-paths -
        // /share survives a rebuild the same way /data does, it's just
        // visible to every addon instead of only this one.
        var persistedSet = new HashSet<string>([.. persistentPaths, .. sharedPaths], StringComparer.Ordinal);
        var atRisk = analysis.PersistentPathCandidates
            .Select(c => c.Path)
            .Concat(analysis.Volumes.Where(v => !v.ReadOnly).Select(v => v.ContainerPath))
            .Select(p => p.Length > 1 ? p.TrimEnd('/') : p)
            .Where(p => !persistedSet.Contains(p) && p != "/data" && !p.StartsWith("/data/", StringComparison.Ordinal))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(p => p, StringComparer.Ordinal)
            .ToList();

        if (persistentPaths.Count > 0 || atRisk.Count > 0)
        {
            sb.AppendLine("## Persistent data");
            sb.AppendLine();

            if (persistentPaths.Count > 0 && entrypointWrapped)
            {
                sb.AppendLine("Home Assistant only keeps `/data` across a rebuild or update — anything an app " +
                               "writes elsewhere is lost. These paths are kept by turning each into a symlink " +
                               "into `/data` when the addon starts (the app keeps writing where it always did; " +
                               "the first start moves the image's own copy of the directory over, and after that " +
                               "`/data` always wins, so an update never overwrites real data):");
                sb.AppendLine();
                foreach (var p in persistentPaths)
                {
                    sb.AppendLine($"- `{p}` → `{PersistenceDetector.TargetFor(p)}`");
                }

                sb.AppendLine();
                sb.AppendLine("This needs the container to start as root. If this image runs as a non-root " +
                               "`USER`, the symlinks are skipped (with a message in the addon's log) and these " +
                               "paths are not kept.");
                sb.AppendLine();
            }
            else if (persistentPaths.Count > 0)
            {
                sb.AppendLine("**Warning:** these paths were asked to be kept, but addon-forge could not wrap this " +
                               "addon's entrypoint (no shell in the final build stage, or no ENTRYPOINT/CMD to " +
                               "preserve), so they are **not** persisted and will be lost on an update:");
                sb.AppendLine();
                foreach (var p in persistentPaths)
                {
                    sb.AppendLine($"- `{p}`");
                }

                sb.AppendLine();
            }

            if (atRisk.Count > 0)
            {
                sb.AppendLine("**Not persisted:** the upstream image looks like it keeps data at the following " +
                               "paths, which Home Assistant does not preserve across a rebuild. Choose them on " +
                               "this addon's page in addon-forge (\"Persistent data\") if the app stores anything " +
                               "there that should survive an update:");
                sb.AppendLine();
                foreach (var p in atRisk)
                {
                    sb.AppendLine($"- `{p}`");
                }

                sb.AppendLine();
            }
        }

        if (sharedPaths.Count > 0)
        {
            sb.AppendLine("## Shared with other addons");
            sb.AppendLine();

            if (entrypointWrapped)
            {
                sb.AppendLine("These paths are symlinked into this addon's own `/share/" + request.Slug + "/...` " +
                               "when it starts (same mechanism as persistent data above, just a different " +
                               "destination) so a *different* addon can read them via its own `share:ro` map " +
                               "entry — for example, exposing this addon's own log files to a bouncer/monitoring " +
                               "addon that can't otherwise see inside this one's private `/data`:");
                sb.AppendLine();
                foreach (var p in sharedPaths)
                {
                    sb.AppendLine($"- `{p}` → `{PersistenceDetector.SharedTargetFor(request.Slug, p)}`");
                }

                sb.AppendLine();
                sb.AppendLine("This addon's own `map:` was given `share:rw` automatically, since it needs to " +
                               "write there itself. This needs the container to start as root, same as " +
                               "persistent data — if this image runs as a non-root `USER`, the symlinks are " +
                               "skipped (with a message in the addon's log) and nothing is shared.");
                sb.AppendLine();
            }
            else
            {
                sb.AppendLine("**Warning:** these paths were asked to be shared, but addon-forge could not wrap " +
                               "this addon's entrypoint (no shell in the final build stage, or no ENTRYPOINT/CMD " +
                               "to preserve), so they are **not** shared:");
                sb.AppendLine();
                foreach (var p in sharedPaths)
                {
                    sb.AppendLine($"- `{p}`");
                }

                sb.AppendLine();
            }
        }

        sb.AppendLine("## Updates");
        sb.AppendLine();
        sb.AppendLine("This addon's files are regenerated by addon-forge when a new version is detected " +
                       "upstream. Installing/updating it in Home Assistant is always a manual step — go to " +
                       "**Settings → Add-ons → Add-on Store → Check for updates**.");

        return sb.ToString();
    }

    public static string BuildChangelogEntry(AddonGenerationRequest request)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"## {request.Version} - {DateTimeOffset.UtcNow:yyyy-MM-dd}");
        sb.AppendLine();
        sb.AppendLine($"- Generated from {request.SourceRepoUrl} @ `{request.Ref}`.");
        sb.AppendLine();
        return sb.ToString();
    }
}
